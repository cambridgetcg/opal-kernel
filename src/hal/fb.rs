/// Initialize the framebuffer from the FDT's `simple-framebuffer` node.
///
/// Called by `board::apple::init()` after the FDT parser is ready. This
/// function:
///
/// 1. Finds the `simple-framebuffer` node by `compatible = "simple-framebuffer"`.
/// 2. Reads `width`, `height`, `stride` properties as u32s.
/// 3. Reads the `reg` property for the physical base address + size.
/// 4. Maps the framebuffer region as Normal non-cacheable via
///    [`ioremap_framebuffer`].
/// 5. Stores the virtual base and geometry in statics so `Framebuffer::new()`
///    can blit into it.
///
/// Returns `true` if the framebuffer was successfully initialized.
pub fn init_from_fdt(
    fdt: &crate::arch::aarch64::fdt::Fdtr,
) -> bool {
    // Find the simple-framebuffer node. The compatible string is
    // "simple-framebuffer" — the standard Linux binding for a
    // bootloader-provided linear framebuffer.
    let fb_node = match fdt.find_by_compatible("simple-framebuffer") {
        Some(n) => n,
        None => return false,
    };

    // Read geometry.
    let width = fdt.prop_u32(&fb_node, "width").unwrap_or(0) as usize;
    let height = fdt.prop_u32(&fb_node, "height").unwrap_or(0) as usize;
    let stride = fdt.prop_u32(&fb_node, "stride").unwrap_or(0) as usize;

    if width == 0 || height == 0 || stride == 0 {
        println!("fb: invalid geometry {width}x{height} stride={stride}");
        return false;
    }

    // Read the physical base from `reg`. On Apple devicetrees,
    // #address-cells=2 and #size-cells=2, so reg is:
    // base_hi, base_lo, size_hi, size_lo — four u32 cells.
    let mut cells = fdt.prop_cells(&fb_node, "reg");
    let base_hi = cells.next().unwrap_or(0) as u64;
    let base_lo = cells.next().unwrap_or(0) as u64;
    let fb_pa = ((base_hi << 32) | base_lo) as usize;

    if fb_pa == 0 {
        println!("fb: null physical base from FDT");
        return false;
    }

    // Translate to the kernel's virtual alias.
    let fb_va = crate::arch::aarch64::mmu::phys_to_virt(fb_pa);

    // Map the framebuffer as Normal non-cacheable. The framebuffer is
    // RAM-backed display memory: Normal (not Device) for performance, but
    // non-cacheable because the display controller reads it directly.
    //
    // We map the first 16 KiB page of the framebuffer. A full-screen
    // framebuffer (e.g. 2560×1600 × 4 bytes = ~16 MB) would need many
    // pages; for the teaching kernel's text console, the first page is
    // enough to prove the path. A real driver would map the entire
    // stride × height region — but this is the first rung.
    match crate::arch::aarch64::mmu::ioremap_framebuffer(fb_va, fb_pa) {
        Ok(()) => {
            unsafe {
                FB_WIDTH = width;
                FB_HEIGHT = height;
                FB_STRIDE = stride;
            }
            FB_VA.store(fb_va, Ordering::Relaxed);
            println!(
                "fb: {width}x{height} stride={stride} pa={fb_pa:#x} va={fb_va:#x} — display live"
            );
            true
        }
        Err(e) => {
            println!(
                "fb: failed to map PA {fb_pa:#x} -> VA {fb_va:#x}: {e:?}"
            );
            false
        }
    }
}

/// Has the framebuffer been initialized?
pub fn is_active() -> bool {
    Framebuffer::is_active()
}

/// Construct a `Framebuffer` console handle. Before `init_from_fdt` has
/// run, writes are silently dropped (the framebuffer base is 0).
pub fn console() -> Framebuffer {
    Framebuffer::new()
}