//! Simple framebuffer text console — blitting characters into iBoot's display.
//!
//! On Apple Silicon, m1n1 republishes iBoot's framebuffer as a
//! `simple-framebuffer` FDT node. This is the only display path guaranteed
//! on every machine — and the exact bring-up trick early Asahi used.
//!
//! The FDT node provides:
//! - `reg`: physical base address + size of the framebuffer memory
//! - `width`: pixels per scanline
//! - `height`: scanlines
//! - `stride`: bytes per scanline (may exceed width × 4 due to padding)
//! - `format`: pixel format (typically `x8r8g8b8` = 0xa1R5G5B5... no —
//!   the `simple-framebuffer` binding uses string names: "x8r8g8b8",
//!   "r5g6b5", "a8r8g8b8", etc.)
//!
//! This driver implements `core::fmt::Write` so it can be used as a
//! console alongside the s5l UART. It maintains a cursor (column, row)
//! and scrolls when the last row overflows.
//!
//! ## Font
//!
//! A minimal 8×16 bitmap font is embedded (256 glyphs × 16 bytes each).
//! The font covers the printable ASCII range (0x20–0x7E); control
//! characters and non-ASCII bytes render as a space or `?`.
//!
//! ## Pixel format
//!
//! Only `x8r8g8b8` (32-bit BGRA/XRGB) is supported initially — it is the
//! format m1n1/iBoot uses on every Apple Silicon Mac tested. The pixel
//! is laid out in memory as `[B, G, R, X]` on little-endian (which
//! aarch64 is), so writing a `u32` value `0x00RRGGBB` produces the
//! correct pixel.
//!
//! ## Memory attributes
//!
//! The framebuffer is RAM-backed display memory. It must be mapped
//! Normal (not Device) for performance — but non-cacheable, because
//! the display controller reads it directly and cache would cause
//! stale pixels. MAIR slot 2 (`0x44` = inner+outer non-cacheable) is
//! the dedicated attribute, applied via [`ioremap_framebuffer`].
//!
//! See docs/02-hal-and-apple-silicon.md §3 item 5 for the spec.

#![allow(dead_code)] // No Apple board is active on QEMU; this skeleton
