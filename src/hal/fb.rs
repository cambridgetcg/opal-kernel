/// A simple framebuffer text console.
///
/// The framebuffer's base address, width, height, and stride are discovered
/// from the FDT's `simple-framebuffer` node and stored in statics during
/// [`init_from_fdt`]. This struct is zero-sized and `Copy`, mirroring the
/// UART drivers — a console conjurable anywhere, including the panic path.
///
/// Before `init_from_fdt` has run, `FB_VA` is 0 and all writes are no-ops.
#[derive(Clone, Copy)]
pub struct Framebuffer;

impl Framebuffer {
    pub const fn new() -> Self {
        Self
    }

    /// Is the framebuffer initialized and usable?
    fn is_active() -> bool {
        FB_VA.load(Ordering::Relaxed) != 0
    }

    /// Write one pixel at (x, y) with color `c`.
    #[inline]
    fn put_pixel(x: usize, y: usize, c: u32) {
        let va = FB_VA.load(Ordering::Relaxed);
        if va == 0 {
            return;
        }
        // SAFETY: va is the mapped framebuffer base; x < width and y < height
        // is guaranteed by the caller (glyph blit checks bounds). The stride
        // is bytes per scanline. We write a u32 to the pixel's address.
        let stride = unsafe { FB_STRIDE };
        let offset = y * stride + x * 4;
        let ptr = (va + offset) as *mut u32;
        unsafe { ptr::with_exposed_provenance_mut::<u32>(ptr as usize).write_volatile(c) };
    }

    /// Blit one glyph at pixel position (px, py).
    fn blit_glyph(ch: u8, px: usize, py: usize) {
        let glyph = if ch < 128 { &FONT[ch as usize] } else { &FONT[b'?' as usize] };
        let fb_width = unsafe { FB_WIDTH };
        let fb_height = unsafe { FB_HEIGHT };

        for row in 0..GLYPH_H {
            let bits = glyph[row];
            let dy = py + row;
            if dy >= fb_height {
                break;
            }
            for col in 0..GLYPH_W {
                let dx = px + col;
                if dx >= fb_width {
                    break;
                }
                let on = (bits >> (7 - col)) & 1 != 0;
                Self::put_pixel(dx, dy, if on { FG } else { BG });
            }
        }
    }

    /// Clear the entire screen.
    #[allow(dead_code)]
    pub fn clear() {
        if !Self::is_active() {
            return;
        }
        let va = FB_VA.load(Ordering::Relaxed);
        let width = unsafe { FB_WIDTH };
        let height = unsafe { FB_HEIGHT };
        let stride = unsafe { FB_STRIDE };

        for y in 0..height {
            let row_ptr = (va + y * stride) as *mut u32;
            for x in 0..width {
                // SAFETY: the framebuffer is mapped Normal-NC, width * 4 <= stride.
                unsafe {
                    ptr::with_exposed_provenance_mut::<u32>(row_ptr.add(x) as usize)
                        .write_volatile(BG);
                }
            }
        }
        CURSOR_COL.store(0, Ordering::Relaxed);
        CURSOR_ROW.store(0, Ordering::Relaxed);
    }

    /// Scroll up by one text row (GLYPH_H pixels).
    fn scroll() {
        let va = FB_VA.load(Ordering::Relaxed);
        if va == 0 {
            return;
        }
        let width = unsafe { FB_WIDTH };
        let height = unsafe { FB_HEIGHT };
        let stride = unsafe { FB_STRIDE };

        // Copy each scanline up by GLYPH_H pixels.
        for y in GLYPH_H..height {
            let src = (va + y * stride) as *const u32;
            let dst = (va + (y - GLYPH_H) * stride) as *mut u32;
            for x in 0..width {
                unsafe {
                    let px = ptr::with_exposed_provenance::<u32>(src.add(x) as usize)
                        .read_volatile();
                    ptr::with_exposed_provenance_mut::<u32>(dst.add(x) as usize)
                        .write_volatile(px);
                }
            }
        }

        // Clear the bottom GLYPH_H scanlines.
        for y in (height - GLYPH_H)..height {
            let dst = (va + y * stride) as *mut u32;
            for x in 0..width {
                unsafe {
                    ptr::with_exposed_provenance_mut::<u32>(dst.add(x) as usize)
                        .write_volatile(BG);
                }
            }
        }
    }

    /// Write one character to the framebuffer console.
    fn write_char(ch: u8) {
        if !Self::is_active() {
            return;
        }

        let width = unsafe { FB_WIDTH };
        let height = unsafe { FB_HEIGHT };
        let cols = width / GLYPH_W;
        let rows = height / GLYPH_H;

        if ch == b'\n' {
            CURSOR_COL.store(0, Ordering::Relaxed);
            let new_row = CURSOR_ROW.fetch_add(1, Ordering::Relaxed) + 1;
            if new_row >= rows {
                Self::scroll();
                CURSOR_ROW.store(rows - 1, Ordering::Relaxed);
            }
            return;
        }

        if ch == b'\r' {
            CURSOR_COL.store(0, Ordering::Relaxed);
            return;
        }

        // Translate \n to \r\n for serial-style text (like the UART drivers).
        let ch = if ch == b'\r' { b'\n' } else { ch };

        let col = CURSOR_COL.load(Ordering::Relaxed);
        let _row = CURSOR_ROW.load(Ordering::Relaxed); // read to check overflow below

        if col >= cols {
            CURSOR_COL.store(0, Ordering::Relaxed);
            let new_row = CURSOR_ROW.fetch_add(1, Ordering::Relaxed) + 1;
            if new_row >= rows {
                Self::scroll();
                CURSOR_ROW.store(rows - 1, Ordering::Relaxed);
            }
        }

        let col = CURSOR_COL.load(Ordering::Relaxed);
        let row = CURSOR_ROW.load(Ordering::Relaxed);
        let px = col * GLYPH_W;
        let py = row * GLYPH_H;

        Self::blit_glyph(ch, px, py);
        CURSOR_COL.store(col + 1, Ordering::Relaxed);
    }
}

impl fmt::Write for Framebuffer {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        for b in s.bytes() {
            // Match the UART convention: \n -> \r\n. The framebuffer's
            // write_char handles \n as a line break; we add \r for consistency
            // with serial terminals, but the framebuffer ignores \r anyway.
            if b == b'\n' {
                Self::write_char(b'\r');
            }
            Self::write_char(b);
        }
        Ok(())
    }
}

